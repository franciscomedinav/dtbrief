/* Site search for dtbrief.com — client-side only.
   Loads search-index.json (regenerated by tools/build-search-index.py on every
   new post) and filters post titles + excerpts as the user types.
   While a query is active the static browse list (#browse-list) is hidden and
   matching posts render as cards; clearing the query restores the list. */
(function () {
  var input = document.getElementById('site-search');
  var resultsBox = document.getElementById('search-results');
  var meta = document.getElementById('search-meta');
  var browse = document.getElementById('browse-list');
  if (!input || !resultsBox) return;

  var index = null;
  var loaded = false;

  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }
  function words(q) {
    return q.toLowerCase().split(/\s+/).filter(function (w) { return w.length > 0; });
  }
  function matches(item, ws) {
    var hay = (item.title + ' ' + item.excerpt + ' ' + item.date).toLowerCase();
    return ws.every(function (w) { return hay.indexOf(w) !== -1; });
  }
  function render(q) {
    var query = (q || '').trim();
    if (!query) {
      resultsBox.innerHTML = '';
      if (meta) meta.textContent = '';
      if (browse) browse.style.display = '';
      return;
    }
    if (!loaded) {
      if (meta) meta.textContent = 'Search is still loading\u2026';
      return;
    }
    var list = index.filter(function (item) { return matches(item, words(query)); });
    if (browse) browse.style.display = 'none';
    if (meta) {
      meta.textContent = list.length + (list.length === 1 ? ' result' : ' results') +
        ' for \u201c' + query + '\u201d';
    }
    if (!list.length) {
      resultsBox.innerHTML = '';
      return;
    }
    var html = '';
    list.forEach(function (item) {
      html += '<a class="post-card" href="' + esc(item.url) + '">' +
        '<span class="kicker">Top Story</span>' +
        '<h3>' + esc(item.title) + '</h3>' +
        '<p>' + esc(item.excerpt) + '</p>' +
        '<span class="meta">' + esc(item.date) + ' &middot; Episode ' + esc(item.episode) + '</span></a>';
    });
    resultsBox.innerHTML = html;
  }

  fetch('search-index.json')
    .then(function (r) {
      if (!r.ok) throw new Error('index HTTP ' + r.status);
      return r.json();
    })
    .then(function (data) {
      index = data;
      loaded = true;
      render(input.value);
    })
    .catch(function () {
      if (meta) meta.textContent = 'Search is unavailable right now.';
    });

  input.addEventListener('input', function () { render(input.value); });
})();
